"""Conventions every table follows.

- Ids are random UUIDs generated by PostgreSQL: unguessable, and safe to merge.
- Timestamps carry their time zone. `updated_at` is maintained by a database
  trigger (`set_updated_at`, created in the first migration), so it also moves
  when rows are changed outside the ORM.
- Constraint and index names follow NAMING_CONVENTION, so migrations stay stable.
- Every table owned by an office has a `tenant_id` (row-level security: step 1.4).
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import DateTime, FetchedValue, MetaData, func, text
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "pk": "pk_%(table_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "ix": "ix_%(table_name)s_%(column_0_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class IdMixin:
    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True, server_default=text("gen_random_uuid()")
    )


class CreatedAtMixin:
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class TimestampsMixin(CreatedAtMixin):
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), server_onupdate=FetchedValue()
    )
